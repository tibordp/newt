//! Code page 437 — the APPNOTE-mandated encoding for entry names without the
//! UTF-8 flag. The low half is ASCII (control bytes pass through unmapped;
//! they are invalid in filenames either way).

pub fn decode(bytes: &[u8]) -> String {
    bytes
        .iter()
        .map(|&b| {
            if b < 0x80 {
                b as char
            } else {
                HIGH[(b - 0x80) as usize]
            }
        })
        .collect()
}

